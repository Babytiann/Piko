/** Height of the floating capsule tab bar itself. */
export const TAB_BAR_HEIGHT = 80;

/**
 * Total vertical space the tab bar occupies above `insets.bottom`.
 * Use as `pb={insets.bottom + TAB_BAR_CONTENT_HEIGHT}` in tab screens.
 */
export const TAB_BAR_CONTENT_HEIGHT = TAB_BAR_HEIGHT + 8;

/** Horizontal inset between indicator edge and tab-cell edge. */
export const INDICATOR_MARGIN_H = 8;

/** Vertical inset between indicator edge and bar edge. */
export const INDICATOR_MARGIN_V = 10;
